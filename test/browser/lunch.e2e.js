import {test,expect} from '@playwright/test';
test('four family members can vote and revise; ties are not silently broken',async({page})=>{
 await page.goto('/lunch');
 await expect(page.locator('#restaurants article')).toHaveCount(5);
 await expect(page.locator('#restaurants article').first()).toContainText('Yark Green Thai');
 await expect(page.locator('#family button')).toHaveCount(4);
 await page.locator('[data-place="yark"]').click();
 await page.locator('[data-place="phat"]').click();
 await page.locator('[data-place="yark"]').click();
 await page.locator('[data-place="phat"]').click();
 await expect(page.locator('#voter-count')).toHaveText('4 / 4 voted');
 await expect(page.locator('#result-label')).toContainText('TIE');
 await expect(page.locator('#winner-directions')).toBeDisabled();
 await page.locator('#family button').nth(1).click();
 await page.locator('[data-place="yark"]').click();
 await expect(page.locator('#result-title')).toHaveText('Yark Green Thai');
 await expect(page.locator('#winner-directions')).toBeEnabled();
 await page.reload();
 await expect(page.locator('#voter-count')).toHaveText('4 / 4 voted');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('#reset').click();
 await expect(page.locator('#voter-count')).toHaveText('0 / 4 voted');
});
test('private default origin is locally persisted, removable and not in the URL after setup',async({page,context})=>{
 await page.goto('/lunch#origin=Example%20Street%2C%20Katy');
 await expect(page.locator('#origin')).toHaveValue('Example Street, Katy');
 await expect.poll(()=>new URL(page.url()).hash).toBe('');
 await page.reload();
 await expect(page.locator('#origin')).toHaveValue('Example Street, Katy');
 await page.evaluate(()=>{window.open=(url)=>{window.lastMap=url;return null}});
 await page.locator('.restaurant').first().getByRole('button',{name:'Directions'}).click();
 expect(await page.evaluate(()=>new URL(window.lastMap).searchParams.get('origin'))).toBe('Example Street, Katy');
 await context.grantPermissions(['geolocation']);
 await context.setGeolocation({latitude:29.8,longitude:-95.8});
 await page.locator('#gps').click();
 await expect(page.locator('#location-mode')).toContainText('Device location');
 await page.locator('.restaurant').first().getByRole('button',{name:'Directions'}).click();
 expect(await page.evaluate(()=>new URL(window.lastMap).searchParams.get('origin'))).toBe('29.8,-95.8');
 await page.locator('#forget').click();
 await expect(page.locator('#origin')).toHaveValue('');
 await page.reload();
 await expect(page.locator('#origin')).toHaveValue('');
});