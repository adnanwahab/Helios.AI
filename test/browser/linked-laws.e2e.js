import {test,expect} from '@playwright/test';
test('constitution selection updates the database law view and scenario',async({page},info)=>{
 await page.goto('/');
 await expect(page.locator('#ll-status')).toContainText('Database connected');
 await expect(page.locator('#ll-tiles .ll-tile')).toHaveCount(100);
 await page.locator('[data-clause-id="S-002"]').click();
 await expect(page.locator('#ll-links')).toContainText('HGA-011');
 await expect(page.locator('#ll-title')).toHaveText('Homes People Can Afford');
 await expect(page.locator('#ll-tiles [data-law-id="HGA-011"]')).toHaveAttribute('data-related','true');
 await page.locator('#ll-clause-view').click();
 await page.locator('#ll-input-reach').fill('0');
 await expect(page.locator('#ll-result')).toHaveText('100.0');
 await page.locator('#ll-reset').click();
 await expect(page.locator('#ll-result')).not.toHaveText('100.0');
 await page.locator('#ll-edit').click();
 await expect(page.locator('#ll-draft-title')).toHaveValue('Homes People Can Afford');
 await page.locator('#ll-close').click();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('#ll-title').scrollIntoViewIfNeeded();
 await page.screenshot({path:info.outputPath('linked-laws-mobile.png')});
});
test('two-answer quiz previews generated scenario; publishing persists the new law and linked visualization',async({page},info)=>{
 const scenario={metric:'Comfortable waits',lever:'Stops reached',family:0,direction:1,lag:2,effect:35,reach:60,capacity:80,years:8,assumptions:'Fictional toy assumptions, not a forecast.'};
 const draft={title:'Test shaded shuttle stops',category:'Housing and livable cities',sharedGoal:'Improve transit comfort.',illustrativeLocalOption:'Pilot shaded stops.',risksAndSafeguards:'Review safety, accessibility and cost.',suggestedMeasures:['Comfortable waits'],scenario};
 await page.route('**/api/law-drafts/config',r=>r.fulfill({json:{enabled:true,model:'test-transformer'}}));
 let generated=0;
 await page.route('**/api/law-drafts/generate',r=>{generated++;expect(r.request().postDataJSON()).toEqual({problem:'Uncomfortable stops.',change:'Pilot shaded stops.',consent:true});return r.fulfill({json:{draft,source:'openai',model:'test-transformer'}})});
 await page.goto('/');
 await expect(page.locator('#ll-status')).toContainText('Database connected');
 await page.locator('[data-clause-id="S-001"]').click();
 await page.locator('#ll-propose-clause').click();
 await page.locator('#ll-problem').fill('Uncomfortable stops.');
 await page.locator('#ll-change').fill('Pilot shaded stops.');
 await expect(page.locator('#ll-ai-state')).toContainText('Transformer ready');
 await page.locator('#ll-generate').click();
 expect(generated).toBe(0);
 await page.locator('#ll-ai-consent').check();
 await page.locator('#ll-generate').click();
 await expect(page.locator('#ll-review')).toBeVisible();
 await expect(page.locator('#ll-draft-model')).toContainText('Comfortable waits');
 await page.screenshot({path:info.outputPath('linked-law-generated-draft.png')});
 await page.locator('#ll-publish-consent').check();
 await page.locator('#ll-publish').click();
 await expect(page.locator('#ll-title')).toHaveText(draft.title);
 await expect(page.locator('#ll-metric')).toHaveText(scenario.metric);
 await expect(page.locator('#ll-input-years')).toHaveValue('8');
 await page.reload();
 await expect(page.locator('#ll-status')).toContainText('Database connected');
 await page.locator('#ll-community').getByRole('button',{name:draft.title,exact:true}).click();
 await expect(page.locator('#ll-metric')).toHaveText('Comfortable waits');
 await expect(page.locator('#ll-input-years')).toHaveValue('8');
});
