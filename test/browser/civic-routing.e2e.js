import {test,expect} from '@playwright/test';
const activeClause=page=>page.locator('#constitution-list .clause-card[aria-pressed="true"]');
const activeLaw=page=>page.locator('#linked-laws [data-law-id][aria-pressed="true"]');
test('live clause review is shared by default; position and pending comment survive refresh',async({page,browser})=>{
 await page.goto('/');
 await expect(page.locator('#review-mode')).toHaveText('Shared');
 await page.locator('[data-clause-id="S-006"]').click();
 await expect(activeClause(page)).toHaveAttribute('data-clause-id','S-006');
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-081');
 expect(new URL(page.url()).searchParams.get('clause')).toBe('S-006');
 await page.locator('[data-clause-vote="support"]').click();
 await expect(page.locator('#clause-status')).toContainText('Position recorded in the database');
 await expect(page.locator('[data-clause-vote="support"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('#clause-comment').fill('Test private pending review note.');
 await page.locator('#post-comment').click();
 await expect(page.locator('#comment-status')).toContainText('Confirm');
 await page.locator('#comment-consent').check();
 await page.locator('#post-comment').click();
 await expect(page.locator('#comment-status')).toContainText('Saved to database');
 await expect(page.locator('#clause-comments')).toContainText('pending moderation');
 expect(page.url()).not.toContain('pending');
 await page.reload();
 await expect(page.locator('#review-mode')).toHaveText('Shared');
 await expect(activeClause(page)).toHaveAttribute('data-clause-id','S-006');
 await expect(page.locator('[data-clause-vote="support"]')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#clause-comments')).toContainText('Test private pending review note.');
 const other=await browser.newPage();
 try{
  await other.goto(page.url());
  await expect(other.locator('#review-mode')).toHaveText('Shared');
  await expect(other.locator('#clause-real')).toContainText('1 support');
  await expect(other.locator('#clause-comments')).not.toContainText('Test private pending review note.');
  await expect(other.locator('[data-clause-vote="support"]')).toHaveAttribute('aria-pressed','false');
 }finally{await other.close()}
});
test('law and clause routes restore both selections on refresh and browser back/forward',async({page})=>{
 await page.goto('/');
 await expect(page.locator('#ll-status')).toContainText('Database connected');
 await page.locator('[data-clause-id="S-002"]').click();
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-011');
 await expect(page).toHaveURL(/clause=S-002&law=HGA-011#review-title$/);
 await page.locator('#ll-links button').filter({hasText:'HGA-012'}).click();
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-012');
 await expect(page).toHaveURL(/clause=S-002&law=HGA-012#ll-detail$/);
 await page.reload();
 await expect(activeClause(page)).toHaveAttribute('data-clause-id','S-002');
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-012');
 await page.locator('[data-clause-id="S-004"]').click();
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-040');
 await page.goBack();
 await expect(activeClause(page)).toHaveAttribute('data-clause-id','S-002');
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-012');
 await page.goForward();
 await expect(activeClause(page)).toHaveAttribute('data-clause-id','S-004');
 await expect(activeLaw(page)).toHaveAttribute('data-law-id','HGA-040');
});
test('database outage never silently records practice votes; opt-in practice remains local',async({page})=>{
 await page.route('**/api/constitution',r=>r.fulfill({status:503,json:{error:'Test database offline'}}));
 const writes=[];page.on('request',r=>{if(r.method()==='POST'&&r.url().includes('/api/constitution'))writes.push(r.url())});
 await page.goto('/');
 await expect(page.locator('#review-mode')).toHaveText('Unavailable');
 await expect(page.locator('#board-status')).toContainText('nothing was saved');
 await expect(page.locator('[data-clause-vote="support"]')).toBeDisabled();
 await expect(page.locator('#post-comment')).toBeDisabled();
 await page.locator('#board-practice').click();
 await expect(page.locator('#review-mode')).toHaveText('Practice');
 await page.locator('[data-clause-vote="support"]').click();
 await expect(page.locator('#clause-status')).toContainText('Practice position');
 expect(writes).toEqual([]);
 await page.unroute('**/api/constitution');
 await page.locator('#board-connect').click();
 await expect(page.locator('#review-mode')).toHaveText('Shared');
 await expect(page.locator('[data-clause-vote="support"]')).toHaveAttribute('aria-pressed','false');
 expect(writes).toEqual([]);
});
