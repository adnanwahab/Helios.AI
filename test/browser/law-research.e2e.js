import {test,expect} from '@playwright/test';
test('100-law research dashboard runs and restores a measured baseline in Consensus World',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.addInitScript(()=>Object.defineProperty(navigator,'gpu',{value:undefined,configurable:true}));
 await page.route('**/api/law-board',r=>r.fulfill({status:503,body:'Unavailable'}));
 await page.goto('/public/law-research.html?law=HGA-031');
 await expect(page.locator('#law-rows button[data-law]')).toHaveCount(100);
 await expect(page.locator('#law-id')).toContainText('HGA-031');
 await expect(page.locator('#coverage')).toHaveText('0 / 100');
 await page.locator('#search').fill('HGA-031');
 await expect(page.locator('#law-rows button[data-law]')).toHaveCount(1);
 await page.locator('#question').fill('How would the pilot expand childcare capacity?');
 await page.locator('#save-note').click();
 await expect(page.locator('#notes-count')).toHaveText('1');
 await page.locator('#run-one').click();
 await expect(page.locator('#run-status')).toContainText('Complete · 1 laws');
 await expect(page.locator('#baseline-source')).toContainText('100,000 agents');
 await expect(page.locator('#open-baseline')).toBeVisible();
 await expect(page.locator('#objections progress')).toHaveCount(8);
 await expect(page.locator('#human-feedback')).toContainText('unavailable');
 await page.reload();
 await expect(page.locator('#question')).toHaveValue('How would the pilot expand childcare capacity?');
 await expect(page.locator('#open-baseline')).toBeVisible();
 await page.locator('#open-baseline').click();
 await expect(page.locator('#status')).toContainText('Research baseline restored');
 await expect(page.locator('#draft-source')).toContainText('HGA-031');
 await expect(page.locator('#count')).toHaveText('100,000 / 100,000 evaluated');
 await expect(page.locator('#baseline')).not.toHaveValue('');
 await page.locator('#effect-0').selectOption('1');
 await page.locator('#run').click();
 await expect(page.locator('#status')).toContainText('round complete');
 await expect(page.locator('#compare-note')).toContainText('Matched IDs');
});
test('homepage links dashboard and mobile remains within viewport',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.route('**/api/law-board',r=>r.fulfill({status:503,body:'Unavailable'}));
 await page.goto('/');
 await expect(page.locator('#law-research-link')).toHaveAttribute('href','./public/law-research.html');
 await page.locator('#law-research-link').click();
 await expect(page.locator('#law-rows button[data-law]')).toHaveCount(100);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
