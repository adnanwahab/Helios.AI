import {test,expect} from '@playwright/test';
test('grid mystery links local drafts, model controls and scripted chat',async({page})=>{
  await page.goto('/grid');
  await expect(page.getByRole('heading',{name:'The Missing Tomorrow.'})).toBeVisible();
  await page.locator('#journal-a').fill('Accessible transit connections.\nProtect neighborhoods from flooding.');
  await page.locator('#journal-b').fill('Protect neighborhoods from flooding.');
  await page.locator('#merge').click();
  await expect(page.locator('#constitution')).toHaveValue('Accessible transit connections.\nProtect neighborhoods from flooding.');
  await page.locator('#generate').click();
  await expect(page.locator('#bill-count')).toHaveText('100 / 100 draft proposals');
  await expect(page.locator('#bills details')).toHaveCount(100);
  await page.locator('#search').fill('HGA-001');
  await expect(page.locator('#bills details')).toHaveCount(1);
  await page.locator('#bills summary').click();
  await expect(page.locator('#bills')).toContainText('Implementation option:');
  await page.locator('[data-preset="all"]').click();
  await expect(page.locator('#transit-total')).toHaveText('20');
  await page.locator('#inspect').click();
  await page.locator('#message').fill('What did the engineer miss?');
  await page.locator('#chat-form button').click();
  await expect(page.locator('#messages')).toContainText('We tracked the opening milestone');
  await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#theory').selectOption('b');
  await page.locator('#solve').click();
  await expect(page.locator('#verdict')).toContainText('CASE CLOSED');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('#reset').click();
  await expect(page.locator('#solve')).toBeDisabled();
  await expect(page.locator('#bills details')).toHaveCount(0);
});