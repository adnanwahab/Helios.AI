import {test,expect} from '@playwright/test';
test('grid mystery links local drafts, model controls and scripted chat',async({page})=>{
  await page.goto('/grid');
  await expect(page.getByRole('heading',{name:'The Missing Tomorrow.'})).toBeVisible();
  await page.locator('#journal-a').fill('Accessible transit connections.\nProtect neighborhoods from flooding.');
  await page.locator('#journal-b').fill('Protect neighborhoods from flooding.');
  await page.locator('#merge').click();
  await expect(page.locator('#constitution')).toHaveValue('Accessible transit connections.\nProtect neighborhoods from flooding.');
  await page.locator('#generate').click();
  await expect(page.locator('#bill-count')).toHaveText('100 / 100 draft proposals');
  await expect(page.locator('#bills details')).toHaveCount(100);
  await page.locator('#search').fill('HGA-001');
  await expect(page.locator('#bills details')).toHaveCount(1);
  await page.locator('#bills summary').click();
  await expect(page.locator('#bills')).toContainText('Implementation option:');
  await page.locator('[data-preset="all"]').click();
  await expect(page.locator('#transit-total')).toHaveText('20');
  await page.locator('#inspect').click();
  await page.locator('#message').fill('What did the engineer miss?');
  await page.locator('#chat-form button').click();
  await expect(page.locator('#messages')).toContainText('We tracked the opening milestone');
  await expect(page.locator('#solve')).toBeEnabled();
  await page.locator('#theory').selectOption('b');
  await page.locator('#solve').click();
  await expect(page.locator('#verdict')).toContainText('CASE CLOSED');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('#reset').click();
  await expect(page.locator('#solve')).toBeDisabled();
  await expect(page.locator('#bills details')).toHaveCount(0);
});
test('chapter one is a branching modal with edit, deep linking and local handoffs',async({page})=>{
  await page.goto('/grid?story=1');
  const dialog=page.locator('#story-modal');
  await expect(dialog).toBeVisible();
  await expect(page.locator('#story-canvas')).toBeVisible();
  await expect(page.locator('#story-heading')).toContainText('A message from a future');
  await dialog.getByRole('button',{name:/Show me the missing page/}).click();
  await expect(page.locator('#story-heading')).toContainText('One hundred proposals');
  await dialog.getByRole('button',{name:/Open the constitution editor/}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('#constitution')).toBeFocused();
  await page.locator('#constitution').fill('A named owner for every draft.');
  await page.locator('#story-open').click();
  await expect(page.locator('#story-heading')).toContainText('One hundred proposals');
  await dialog.getByRole('button',{name:/Compare the resident/}).click();
  await expect(page.locator('#story-heading')).toContainText('I could not reach it');
  await dialog.getByRole('button',{name:/test what a connection/}).click();
  await expect(page.locator('#story-heading')).toContainText('Two cities');
  await dialog.getByRole('button',{name:/Open the city simulator/}).click();
  await expect(page.locator('#year')).toBeFocused();
  await expect(page.locator('#constitution')).toHaveValue('A named owner for every draft.');
  await page.locator('#story-open').click();
  await dialog.getByRole('button',{name:'Restart'}).click();
  await expect(page.locator('#story-heading')).toContainText('A message from a future');
  await page.setViewportSize({width:390,height:844});
  expect(await dialog.evaluate(d=>d.scrollWidth<=d.clientWidth+1)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
});

test('population chamber is inspectable, deterministic and remains local',async({page})=>{
 await page.goto('/grid?story=population');
 const chamber=page.locator('#population-chamber');
 await expect(chamber).toBeVisible();
 await expect(page.locator('#pop-status')).toContainText('16,384');
 await expect(page.locator('#pop-status')).toContainText('8,000,000,000');
 await page.locator('#pop-id').fill('8000000000');
 await page.locator('#pop-inspect').click();
 await expect(page.locator('#pop-judgment')).toContainText('8,000,000,000');
 const memories=await page.locator('#pop-memories').innerText();
 await page.locator('#pop-proposal').selectOption('1');
 await page.locator('#pop-run').click();
 await expect(page.locator('#pop-memories')).toHaveText(memories);
 await expect(page.locator('#pop-tallies strong')).toHaveCount(3);
 await page.setViewportSize({width:390,height:844});
 expect(await page.locator('#story-modal').evaluate(d=>d.scrollWidth<=d.clientWidth+1)).toBe(true);
 await page.getByRole('button',{name:/Open the constitution editor/}).click();
 await expect(page.locator('#constitution')).toBeFocused();
 await page.locator('#story-open').click();
 await expect(chamber).toBeVisible();
});
