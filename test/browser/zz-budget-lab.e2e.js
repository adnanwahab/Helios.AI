import {test,expect} from '@playwright/test';
test('budget toggle, balanced preview, apply, undo, floors and local export',async({page})=>{
 const api=[];page.on('request',r=>{if(r.url().includes('/api/'))api.push(r.url())});
 await page.goto('/public/reimagine-government.html');
 await expect(page.locator('#budget-lab')).toBeHidden();
 await page.locator('#budget-open').click();
 await expect(page.locator('#budget-lab')).toBeVisible();
 await expect(page.locator('#budget-allocations .budget-allocation')).toHaveCount(7);
 await expect(page.locator('#budget-baseline-total')).toHaveText('$100m');
 await expect(page.locator('#budget-proposed-total')).toHaveText('$100m');
 await expect(page.locator('#budget-balance')).toHaveText('$0m');
 await expect(page.locator('#budget-transfer-label')).toContainText('$2m');
 await expect(page.locator('#budget-impacts')).toContainText('40 accessible shaded stop-years');
 await expect(page.locator('#budget-impacts')).toContainText('20 staff-equivalent years');
 await expect(page.locator('[data-category="transport"] .budget-delta')).toHaveText('+$2m');
 await page.locator('#budget-apply').click();
 await expect(page.locator('#budget-history')).toContainText('$2m');
 await expect(page.locator('#budget-apply')).toBeDisabled();
 await expect(page.locator('#budget-amount')).toBeDisabled();
 await expect(page.locator('#budget-impacts')).toContainText('40 accessible shaded stop-years');
 await page.locator('#budget-from').selectOption('housing');
 await page.locator('#budget-amount').fill('3');
 await expect(page.locator('#budget-proposed-total')).toHaveText('$100m');
 await page.locator('#budget-apply').click();
 await expect(page.locator('#budget-history li')).toHaveCount(2);
 await page.locator('#budget-undo').click();
 await expect(page.locator('#budget-history li')).toHaveCount(1);
 const download=page.waitForEvent('download');await page.locator('#budget-export').click();
 expect((await download).suggestedFilename()).toBe('helios-budget-draft.json');
 await page.locator('#budget-reset').click();
 await expect(page.locator('#budget-history')).toHaveText('No applied changes yet.');
 await expect(page.locator('[data-category="transport"] .budget-delta')).toHaveText('$0m');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(api).toEqual([]);
 await page.goto('/public/reimagine-government.html#budget-lab');
 await expect(page.locator('#budget-lab')).toBeVisible();
 await expect(page.locator('#budget-open')).toHaveAttribute('aria-expanded','true');
});
